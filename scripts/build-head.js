#!/usr/bin/env node
// Stux.Group Services — writes the generated part of every page's <head>.
//
// Usage: node scripts/build-head.js           rewrite the blocks
//        node scripts/build-head.js --check   exit 1 if any block is out of date (CI)
//
// Each page has one block between <!-- head:start ... --> and <!-- head:end -->, holding:
//   - the icon tags (favicon.ico, the 512px PNG, apple-touch-icon and site.webmanifest),
//     identical on every page, 404 included;
//   - on content pages, Open Graph tags and a Discord component embed
//     (<script id="discord:component-embed">, see
//     https://docs.discord.com/developers/link-previews/component-embeds): a richer link
//     preview in Discord, with the Open Graph tags as its fallback. Left out (an HTML comment
//     instead) when the payload would be over Discord's 3,000-byte limit, and never on the
//     404 page or the /changelog/ redirect.
// Titles and descriptions come from each page's own <title> and meta description, so edit
// those, then re-run this. scripts/build-sitemap.py runs it too.
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const BASE_URL = "https://" + fs.readFileSync(path.join(ROOT, "CNAME"), "utf8").trim();
const SITE_NAME = "Stux.Group Services";
const ACCENT = "#d10f0f"; // Stux.Group red
const ICON_URL = BASE_URL + "/assets/img/icon.png";
const MAX_BYTES = 3000;
const START = "<!-- head:start: generated by scripts/build-head.js, edit that and re-run it -->";
const END = "<!-- head:end -->";

const FAVICON_TAGS = [
  '<link rel="icon" href="/favicon.ico" sizes="48x48">',
  '<link rel="icon" type="image/png" sizes="512x512" href="/assets/img/icon-512.png">',
  '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
  '<link rel="manifest" href="/site.webmanifest">',
];

// ---- Discord component embeds -------------------------------------------------------------

/** Escapes Discord markdown so data shows as plain text: a backslash before each special character. */
function discordMd(s) {
  // Inline formatting, link brackets and backslashes anywhere; headings, quotes and lists only at a line start.
  return String(s).replace(/([\\*_~`|[\]])/g, "\\$1").replace(/^([#>-])/gm, "\\$1");
}

function discordText(markdown) {
  return { type: 10, content: markdown };
}

/** A row of link buttons from [[label, absolute URL], ...]. Buttons may only use these keys. */
function discordButtons(links) {
  return { type: 1, components: links.map(([label, url]) => ({ type: 2, style: 5, label: String(label).slice(0, 80), url })) };
}

/** Text with the Stux.Group icon beside it. */
function discordSection(markdown) {
  return { type: 9, components: [discordText(markdown)], accessory: { type: 11, media: { url: ICON_URL } } };
}

/** The JSON for a payload, or null when it's over Discord's 3,000-byte limit. */
function discordPayload(components, accent = ACCENT) {
  const payload = { component: { type: 17, accent_color: parseInt(accent.replace(/^#/, ""), 16), components } };
  // "</" can't close the <script> early; JSON reads "<\/" back as "</".
  const json = JSON.stringify(payload).replace(/<\//g, "<\\/");
  return Buffer.byteLength(json, "utf8") > MAX_BYTES ? null : json;
}

/** The <script> tag, or a comment when it would be over the limit (Discord then shows the Open Graph preview). */
function discordEmbed(components, accent = ACCENT) {
  const json = discordPayload(components, accent);
  return json === null
    ? `<!-- discord:component-embed left out: over ${MAX_BYTES} bytes -->`
    : `<script id="discord:component-embed" type="application/json">${json}</script>`;
}

const abs = (p) => BASE_URL + p;
const siteLabel = () => `-# [${SITE_NAME}](${abs("/")})\n`;

/** Any page: its name and description, with a way back to the services. */
function pageEmbed(title, desc, url, extra = [], buttons = null) {
  return discordEmbed([
    discordSection(`${siteLabel()}## [${discordMd(title)}](${url})\n${discordMd(desc)}`),
    ...extra,
    discordButtons(buttons || [["Open", url], ["All services", abs("/#services")]]),
  ]);
}

// ---- Reading the pages -------------------------------------------------------------------

function decode(s) {
  return s.replace(/&(amp|lt|gt|quot|#39|mdash|ndash|nbsp);/g, (_, e) =>
    ({ amp: "&", lt: "<", gt: ">", quot: '"', "#39": "'", mdash: "—", ndash: "–", nbsp: " " })[e]);
}
function attr(s) {
  return s.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}
function stripTags(s) {
  return decode(s.replace(/<[^>]+>/g, "")).replace(/\s+/g, " ").trim();
}

/** Every HTML page, as { file, rel, url, html }. */
function pages() {
  const out = [];
  (function walk(dir) {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      if (ent.isDirectory()) {
        if (![".git", ".github", "node_modules", "tests", "scripts"].includes(ent.name)) walk(path.join(dir, ent.name));
      } else if (ent.name.endsWith(".html")) {
        const file = path.join(dir, ent.name);
        const rel = path.relative(ROOT, file).split(path.sep).join("/");
        const url = rel === "404.html" ? null : "/" + rel.replace(/index\.html$/, "");
        out.push({ file, rel, url, html: fs.readFileSync(file, "utf8") });
      }
    }
  })(ROOT);
  return out.sort((a, b) => a.rel.localeCompare(b.rel));
}

function pageTitle(html) {
  const m = html.match(/<title>([\s\S]*?)<\/title>/);
  return m ? decode(m[1].trim()) : SITE_NAME;
}
function pageDesc(html) {
  const m = html.match(/<meta name="description" content="([^"]*)">/);
  return m ? decode(m[1]) : "";
}
/** A content page gets Open Graph tags and an embed; the 404 page and redirects don't. */
function isContentPage(page) {
  return page.url !== null && !/http-equiv="refresh"/i.test(page.html);
}

// ---- Page types --------------------------------------------------------------------------

/** The homepage: what the site is, the hero's counts, and every brand as a link. */
function homeEmbed(html, desc) {
  const stats = {};
  for (const m of html.matchAll(/<strong class="grad">([^<]+)<\/strong><span>([^<]+)<\/span>/g)) stats[decode(m[2])] = decode(m[1]);
  const brandsHtml = (html.split('<h3 class="subhead">Our brands</h3>')[1] || "").split('<h3 class="subhead">')[0];
  const brands = [];
  for (const card of brandsHtml.split("<article").slice(1)) {
    const name = card.match(/<h3>([\s\S]*?)<\/h3>/);
    const site = card.match(/<a href="(https?:\/\/[^"]+)"[^>]*>Website<\/a>/);
    if (name) brands.push(site ? `[${discordMd(stripTags(name[1]))}](${site[1]})` : discordMd(stripTags(name[1])));
  }
  const count = stats["services & sites"] ? `${stats["services & sites"]} services and sites across ${brands.length} brands, with live status where we check it.` : "";
  return discordEmbed([
    discordSection(`# [${SITE_NAME}](${abs("/")})\n**Every Stux.Group brand, service, API and template, in one place.**\n${discordMd(count || desc)}`),
    { type: 14 },
    discordText(`### Our brands\n${brands.join(" · ")}`),
    discordButtons([["Browse services", abs("/#services")], ["Live status", "https://status.stux.group"], ["Stux.Group", "https://stux.group"]]),
  ]);
}

/** The legal hub: every legal page as a link. */
function legalHubEmbed(title, desc, url, html) {
  const links = [];
  for (const m of html.matchAll(/<a href="(\/legal\/[a-z-]+\/)" class="legal-card">[\s\S]*?<div class="legal-card-name">([\s\S]*?)<\/div>/g)) {
    links.push(`[${discordMd(stripTags(m[2]))}](${abs(m[1])})`);
  }
  return pageEmbed(title, desc, url, links.length ? [discordText(links.join(" · "))] : []);
}

/** The changelogs page: the latest version and what kinds of change it made. */
function changelogEmbed(title, desc, url) {
  const md = fs.readFileSync(path.join(ROOT, "CHANGELOG.md"), "utf8").replace(/\r\n/g, "\n");
  const m = md.match(/^## (v\S+)\n([\s\S]*?)(?=^## |(?![\s\S]))/m);
  const extra = [];
  if (m) {
    const kinds = [];
    for (const s of m[2].split(/^### /m).slice(1)) {
      const items = (s.match(/^\s*[-*] /gm) || []).length;
      kinds.push(`${discordMd(s.split("\n")[0].trim())} ${items}`);
    }
    extra.push(discordText(`**Latest: ${discordMd(m[1])}**${kinds.length ? "\n-# " + kinds.join(" · ") : ""}`));
  }
  return pageEmbed(title, desc, url, extra, [["Read the changelogs", url], ["All services", abs("/#services")]]);
}

function embedFor(page) {
  const full = pageTitle(page.html);
  const title = full.replace(/ (—|-|\|) Stux\.Group Services$/, "");
  const desc = pageDesc(page.html);
  const url = abs(page.url);
  if (page.url === "/") return homeEmbed(page.html, desc);
  if (page.url === "/legal/") return legalHubEmbed(title, desc, url, page.html);
  if (page.url === "/changelogs/") return changelogEmbed(title, desc, url);
  return pageEmbed(title, desc, url);
}

function blockFor(page) {
  const lines = [...FAVICON_TAGS];
  if (isContentPage(page)) {
    const full = pageTitle(page.html);
    lines.push(
      '<meta property="og:type" content="website">',
      `<meta property="og:site_name" content="${SITE_NAME}">`,
      `<meta property="og:title" content="${attr(full)}">`,
      `<meta property="og:description" content="${attr(pageDesc(page.html))}">`,
      `<meta property="og:url" content="${attr(abs(page.url))}">`,
      `<meta property="og:image" content="${abs("/assets/img/icon-512.png")}">`,
      '<meta name="twitter:card" content="summary">',
      "<!-- Discord: a custom link preview (the Open Graph tags above are its fallback). -->",
      embedFor(page)
    );
  }
  return lines;
}

/** The page with its block rewritten (or first added, in place of the old icon links). */
function render(page) {
  let html = page.html;
  const startRe = /^([ \t]*)<!-- head:start[^\n]*-->\n[\s\S]*?<!-- head:end -->\n/m;
  let indent;
  let m = html.match(startRe);
  if (m) {
    indent = m[1];
  } else {
    // First run: replace the old remote icon links, or else go just before </head>.
    const old = /^([ \t]*)<link rel="icon"[^\n]*\n(?:[ \t]*<link rel="icon"[^\n]*\n)*/m;
    const o = html.match(old);
    if (o) {
      html = html.replace(old, `${o[1]}${START}\n${END}\n`);
    } else {
      const h = html.match(/^([ \t]*)<\/head>/m);
      const ind = h && h[1] === "" && /\n<meta/.test(html) ? "" : "  ";
      html = html.replace(/^[ \t]*<\/head>/m, `${ind}${START}\n${END}\n</head>`);
    }
    m = html.match(startRe);
    indent = m[1];
  }
  const block = [START, ...blockFor({ ...page, html }), END].map((l) => indent + l).join("\n") + "\n";
  return html.replace(startRe, () => block);
}

function main(argv) {
  const check = argv.includes("--check");
  let stale = 0;
  for (const page of pages()) {
    const next = render(page);
    if (next === page.html) continue;
    if (check) {
      console.error(`${page.rel}: generated <head> block is out of date (run node scripts/build-head.js)`);
      stale++;
    } else {
      fs.writeFileSync(page.file, next);
      console.log(`Wrote ${page.rel}`);
    }
  }
  if (check && stale) process.exit(1);
  if (check) console.log("Every generated <head> block is up to date.");
}

module.exports = { discordMd, discordText, discordButtons, discordSection, discordPayload, discordEmbed, pageEmbed, pages, render, isContentPage, FAVICON_TAGS, MAX_BYTES, ACCENT, BASE_URL };

if (require.main === module) main(process.argv.slice(2));
